/**
 * Returns the verified rule for the programme code, or a structured default rule
 * marked as unverified/estimated with full transparency.
 */
export function getProgrammeRule(code: string): ProgrammeRule {
  const normalized = code.trim().toUpperCase().replace(/\s+/g, '');
  if (VERIFIED_PROGRAMME_RULES[normalized]) {
    return VERIFIED_PROGRAMME_RULES[normalized];
  }

  // Fallback for programmes where specific handbook hasn't been individually indexed:
  // Is it likely a Master's (M...) or Bachelor's (B...)?
  const isPostgraduate = normalized.startsWith('M') || normalized.startsWith('PG');
  const passPercent = isPostgraduate ? 40 : 35;

  return {
    programmeCode: normalized,
    programmeName: `${normalized} Programme`,
    applicableCurriculum: 'Standard IGNOU Evaluation System',
    defaultAssessmentWeightage: { assignment: 0.30, theory: 0.70 },
    defaultMaxMarks: { assignment: 100, theory: 100 },
    passMarks: {
      assignmentPercent: passPercent,
      theoryPercent: passPercent,
      overallPercent: passPercent,
    },
    defaultCreditsPerCourse: 4,
    aggregationMethod: 'credit_weighted',
    roundingDecimals: 2,
    officialSourceReference: 'Standard IGNOU 30:70 Weightage Policy (Provisional)',
    verificationDate: new Date().toISOString().split('T')[0],
    isVerified: false,
    notes: `Calculation applies the universal 30% Continuous Assessment (Assignments) + 70% Term-End Examination weightage standard with ${passPercent}% pass mark. Labelled as an estimate until programme-specific guide is verified.`,
  };
}
